#!/usr/bin/env python3
"""Regenerate both retained LOD recipes and check actual cache/source identities."""
import argparse
import hashlib
import json
from pathlib import Path
import subprocess
import sys

repo = Path(__file__).resolve().parents[2]
experiment = Path(__file__).resolve().parent
parser = argparse.ArgumentParser()
parser.add_argument('--output-root', type=Path, required=True)
args = parser.parse_args()
output = args.output_root.resolve(); output.mkdir(parents=True, exist_ok=False)
receipt = dict(passed=False, regeneratedCaches=[], regeneratedSources=[])


def digest(path):
    return hashlib.sha256(path.read_bytes()).hexdigest()


for version in ('v2-index-lod', 'v3-spatial-lod'):
    frozen = experiment/'native-validation'/version
    recipe = frozen/'recipe/prepare_lod.py'
    code = recipe.read_text()
    for before, after in (
        ('repo = Path(__file__).resolve().parents[2]', 'repo = Path('+repr(str(repo))+')'),
        ('experiment = Path(__file__).resolve().parent', 'experiment = Path('+repr(str(recipe.parent))+')'),
    ):
        assert code.count(before) == 1
        code = code.replace(before, after)
    command = [sys.executable, '-c', '__file__='+repr(str(recipe))+'\n'+code,
               '--output-root', str(output/version)]
    if version == 'v3-spatial-lod': command.append('--clusters')
    result = subprocess.run(command, capture_output=True, text=True, check=True)
    (output/(version+'-stdout.txt')).write_text(result.stdout)
    (output/(version+'-stderr.txt')).write_text(result.stderr)
    expected = json.loads((frozen/'lod-receipt.json').read_text())
    actual = json.loads((output/version/'lod-receipt.json').read_text())
    for old, new in zip(expected['records'], actual['records']):
        for key in ('asset', 'packSha256', 'metadataSha256', 'geometryIdentity', 'metadataBytes'):
            assert old[key] == new[key], (version, key)
        receipt['regeneratedCaches'].append(dict(version=version, asset=old['asset'], sha256=new['metadataSha256']))
    for name in ('resident.c', 'quality.c', 'source/model_wrap.c', 'source/lod.inc')+(
            ('source/cluster_load.inc',) if version == 'v3-spatial-lod' else ()):
        assert (frozen/name).read_bytes() == (output/version/name).read_bytes(), (version, name)
        receipt['regeneratedSources'].append(dict(version=version, name=name, sha256=digest(frozen/name)))
receipt.update(passed=True, originalPacksUnchanged=True, rendererRebuilt=False,
               runnerSha256=digest(Path(__file__)))
(output/'receipt.json').write_text(json.dumps(receipt, indent=2)+'\n')
print('Eight caches and nine actual compiled driver/wrapper/include sources regenerated byte-exactly.')
